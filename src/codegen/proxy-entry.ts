import type { ProxyRewrite } from "../translate/vercel-json.ts";

export const PROXY_ENTRY_FILE = "switchyard-proxy-entry.ts";

// Paths to pass to worker.assets.runWorkerFirst so static assets stay edge-cached and only
// proxied paths invoke the Worker.
export function proxyRunWorkerFirst(proxies: readonly ProxyRewrite[]): string[] {
  return [...new Set(proxies.map((p) => (p.wildcard ? `${p.prefix === "/" ? "" : p.prefix}/*` : p.prefix)))];
}

// A minimal Worker entrypoint that forwards external proxy rewrites from vercel.json
// (such as `/api/:path*` -> `https://api.example.com/:path*`) and serves everything else
// from the ASSETS binding.
export function proxyEntrySource(proxies: readonly ProxyRewrite[]): string {
  const rules = JSON.stringify(proxies, null, 2);
  return `// Generated by Switchyard. Proxies external rewrite rules from vercel.json and serves static assets via ASSETS.
interface ProxyRule {
  prefix: string;
  target: string;
  wildcard: boolean;
}

const RULES: readonly ProxyRule[] = ${rules};

interface Env {
  ASSETS: { fetch(request: Request): Promise<Response> };
}

function matchTarget(pathname: string, search: string): string | null {
  for (const rule of RULES) {
    if (rule.wildcard) {
      const base = rule.prefix === "/" ? "/" : \`\${rule.prefix}/\`;
      if (pathname === rule.prefix || pathname.startsWith(base)) {
        const rest = rule.prefix === "/" ? pathname : pathname.slice(rule.prefix.length);
        return \`\${rule.target}\${rest}\${search}\`;
      }
    } else if (pathname === rule.prefix) {
      return \`\${rule.target}\${search}\`;
    }
  }
  return null;
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    const upstream = matchTarget(url.pathname, url.search);
    if (!upstream) return env.ASSETS.fetch(request);
    const headers = new Headers(request.headers);
    headers.delete("host");
    return fetch(new Request(upstream, { method: request.method, headers, body: request.body, redirect: "manual" }));
  },
};
`;
}
